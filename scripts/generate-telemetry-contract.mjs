import { execFile } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { promisify } from "node:util";

const run = promisify(execFile);

const root = process.cwd();
const schemaPath = path.join(
  root,
  "contracts/telemetry/v1/client-envelope.schema.json",
);
const registryPath = path.join(
  root,
  "contracts/telemetry/v1/client-registry.json",
);
const schema = JSON.parse(await readFile(schemaPath, "utf8"));
const registry = JSON.parse(await readFile(registryPath, "utf8"));

const pascalCase = (value) =>
	value
		.split("_")
		.map((part) =>
			part === "id" ? "ID" : `${part[0].toUpperCase()}${part.slice(1)}`,
		)
		.join("");

const goType = (definition) => {
  if (definition.type === "integer") return "int";
  if (definition.type === "string") return "string";
  if (definition.type === "object") return "map[string]any";
  throw new Error(`unsupported Go schema type: ${definition.type}`);
};

const goRules = Object.entries(schema.properties)
  .map(([name, definition]) => {
    const fields = [
      `Kind: ${JSON.stringify(definition.type)}`,
      `Pattern: ${JSON.stringify(definition.pattern ?? "")}`,
      `MaxProperties: ${definition.maxProperties ?? 0}`,
    ];
    if (definition.const !== undefined) {
      fields.push(`ConstInteger: intPointer(${definition.const})`);
    }
    return `\t${JSON.stringify(name)}: {${fields.join(", ")}},`;
  })
  .join("\n");

const goFields = Object.entries(schema.properties)
  .map(
    ([name, definition]) =>
      `\t${pascalCase(name)} ${goType(definition)} \`json:"${name}"\``,
  )
  .join("\n");

const goRegistry = JSON.stringify(registry);
const goOutput = `// Code generated by scripts/generate-telemetry-contract.mjs. DO NOT EDIT.

package telemetry

const generatedClientRegistryJSON = ${JSON.stringify(goRegistry)}

type ClientEnvelope struct {
${goFields}
}

var generatedClientFieldRules = map[string]clientFieldRule{
${goRules}
}
`;

const valibotExpression = (definition) => {
  let base;
  if (definition.type === "integer") {
    base = "v.pipe(v.number(), v.finite(), v.integer())";
	} else if (definition.type === "string") {
		base = definition.pattern
			? `v.pipe(v.string(), v.regex(/${definition.pattern.replaceAll("/", "\\/")}/))`
			: "v.string()";
  } else if (definition.type === "object") {
    base = `v.pipe(v.record(v.string(), v.union([v.string(), v.pipe(v.number(), v.finite()), v.boolean()])), v.check((input) => Object.keys(input).length <= ${definition.maxProperties}))`;
  } else {
    throw new Error(`unsupported TypeScript schema type: ${definition.type}`);
  }
  if (definition.const !== undefined) {
    return `v.literal(${JSON.stringify(definition.const)})`;
  }
  return base;
};

const tsFields = Object.entries(schema.properties)
  .map(([name, definition]) => `  ${name}: ${valibotExpression(definition)},`)
  .join("\n");

const tsOutput = `// Code generated by scripts/generate-telemetry-contract.mjs. DO NOT EDIT.

import * as v from "valibot";

export const ClientEnvelopeSchema = v.strictObject({
${tsFields}
});

export type ClientEnvelope = v.InferOutput<typeof ClientEnvelopeSchema>;

export const parseClientEnvelopeSchema = (input: unknown): ClientEnvelope =>
  v.parse(ClientEnvelopeSchema, input);

export const clientRegistry = ${JSON.stringify(registry, null, 2)} as const;
`;

const generatedGoPath = path.join(
  root,
  "internal/platform/telemetry/client_contract_generated.go",
);
await writeFile(generatedGoPath, goOutput);
await run("gofmt", ["-w", generatedGoPath]);
await writeFile(
  path.join(
    root,
    "packages/client-telemetry/src/generated/client-contract.schema.ts",
  ),
  tsOutput,
);
